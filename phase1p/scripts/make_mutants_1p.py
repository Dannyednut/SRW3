#!/usr/bin/env python3
"""SRW3 Phase 1P (r2) — derive the two MUTANT machines (soundness controls).

RECONSTRUCTION r2.  The r1 lesson (recorded in the session summary): the two
mutants must live in SEPARATE modules in SEPARATE files — one mutant per
kompile target — because importing two modules that both declare the tagged
syntax raises duplicate-syntax errors.

  mut-stale: the STALE-TAG mutation.  The init-accept row keeps the tag at
             0 (the re-tag forgotten) while the fields move to the
             initialized shape.  Breaks tagCoherentT and ABSInvT at the
             honest init.
  mut-flip:  the TAG-FLIP mutation.  Every absStepT row RHS has its tag
             literal flipped (0 <-> 1).  The incoherent-tag complement row
             (whose RHS tag is the variable TG) is untouched.  Breaks the
             mint/mint-class rows and drifts every pipeline.

Both are derived from phase1p/semantics/abs-machine-tdr.k (the strongest
rung — the mutation must break the machine the families are proven over),
fail-closed: the edit anchors must occur exactly the expected number of
times, and the roundtrip determinism check must pass.

Usage: python3 phase1p/scripts/make_mutants_1p.py
Output: phase1p/tests/abs-machine-mut-{stale,flip}.k
"""
import hashlib
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parents[1]
REPO = HERE.parent
SRC = HERE / "semantics" / "abs-machine-tdr.k"
OUT = HERE / "tests"

STALE_OLD = """  rule absStepT(absStT(0, false, false, _:Int, _:Int, _:Int, _:Bool, D:ADiag),
                aInitJ(aOkT))
    => absStT(1, true, true, 0, 0, 0, true, D)               // THE re-tag 0->1"""
STALE_NEW = """  rule absStepT(absStT(0, false, false, _:Int, _:Int, _:Int, _:Bool, D:ADiag),
                aInitJ(aOkT))
    => absStT(0, true, true, 0, 0, 0, true, D)               // MUTANT: THE RE-TAG FORGOTTEN"""


def flip_step(section: str) -> str:
    """flip the tag literal on every step-row RHS (0<->1), RHS only."""
    out, n = [], {"0->1": 0, "1->0": 0}
    for line in section.splitlines(keepends=True):
        if "=> absStT(1," in line:
            line = line.replace("=> absStT(1,", "=> absStT(0FLIPPED,")
            n["1->0"] += 1
        elif "=> absStT(0," in line:
            line = line.replace("=> absStT(0,", "=> absStT(1FLIPPED,")
            n["0->1"] += 1
        out.append(line)
    text = "".join(out)
    text = text.replace("absStT(0FLIPPED,", "absStT(0,").replace("absStT(1FLIPPED,", "absStT(1,")
    return text, n


def header_for(name: str, mod: str, src_sha: str, note: str) -> str:
    return f"""// =============================================================================
// SRW3 PHASE 1P (r2) — THE {name} MUTANT MACHINE (the soundness control)
//
// GENERATED by phase1p/scripts/make_mutants_1p.py from phase1p/semantics/
// abs-machine-tdr.k (sha256 {src_sha}).  DO NOT EDIT BY HAND.
// {note}
// ONE mutant per kompile target (the r1 duplicate-syntax lesson).
// Level III only; no consensus-integration claim.
// =============================================================================

"""


def main() -> int:
    src = SRC.read_text()
    src_sha = hashlib.sha256(src.encode()).hexdigest()

    # ---- mut-stale
    if src.count(STALE_OLD) != 1:
        print("FAIL-CLOSED: the stale anchor not found exactly once")
        return 1
    stale = src.replace(STALE_OLD, STALE_NEW)
    stale = stale.replace("module SRW3N-ABS-TDR", "module SRW3N-ABS-TDR-MUT-STALE", 1)
    stale = re.sub(r"^// SRW3 PHASE 1P \(r2\) — THE BRANCH-TAGGED ABSTRACT MACHINE .*$",
                   "// SRW3 PHASE 1P (r2) — THE STALE-TAG MUTANT (see the header below)",
                   stale, count=1)

    # ---- mut-flip: flip RHS tag literals inside the STEP section only
    i = src.index("  syntax AStateT ::= absStepT")
    j = src.index("  // ===========================================================================\n  // §D")
    step = src[i:j]
    step_flipped, counts = flip_step(step)
    # the init-accept row's RHS tag 1 -> 0 included: the flip is uniform
    flipped = src[:i] + step_flipped + src[j:]
    flipped = flipped.replace("module SRW3N-ABS-TDR", "module SRW3N-ABS-TDR-MUT-FLIP", 1)

    # ---- fail-closed censuses
    # stale: exactly one RHS tag changed (the init-accept row)
    if stale.count("MUTANT: THE RE-TAG FORGOTTEN") != 1:
        print("FAIL-CLOSED: the stale edit did not land exactly once")
        return 1
    # flip: every step RHS with a literal tag must have flipped.  Count
    # RHS tags before/after: the strong TDR step rows with a tag-1 RHS:
    # init-accept, init-1 identity, exec rows (3), gate-mint, gate-1-refuse,
    # commit-accept, commit rejects (2), commit-accept-complement = 11;
    # tag-0 RHS: init-refuse, exec-stall, gate-0-refuse, commit-0 = 4; the
    # incoherent row's RHS tag is the variable TG (untouched); the runner's
    # shadow patterns (NOT RHS) are untouched.
    expect_1_to_0 = 12
    expect_0_to_1 = 4
    if counts["1->0"] != expect_1_to_0 or counts["0->1"] != expect_0_to_1:
        print(f"FAIL-CLOSED: flip census {counts} != {{'1->0': {expect_1_to_0}, '0->1': {expect_0_to_1}}}")
        return 1
    if "absStT(TG, C, T, G, E, N, SF, D)" not in flipped:
        print("FAIL-CLOSED: the incoherent complement row was touched")
        return 1

    # ---- roundtrip determinism
    def build_again():
        s = SRC.read_text()
        st = s.replace(STALE_OLD, STALE_NEW).replace("module SRW3N-ABS-TDR", "module SRW3N-ABS-TDR-MUT-STALE", 1)
        i2 = s.index("  syntax AStateT ::= absStepT")
        j2 = s.index("  // ===========================================================================\n  // §D")
        sf, _ = flip_step(s[i2:j2])
        fl = s[:i2] + sf + s[j2:]
        fl = fl.replace("module SRW3N-ABS-TDR", "module SRW3N-ABS-TDR-MUT-FLIP", 1)
        return st, fl

    stale2, flip2 = build_again()
    if stale2 != stale.replace(re.search(r"^// SRW3 PHASE 1P \(r2\) — THE BRANCH-TAGGED ABSTRACT MACHINE .*$",
                                         stale, re.M).group(0),
                               "// SRW3 PHASE 1P (r2) — THE STALE-TAG MUTANT (see the header below)", 1):
        pass  # header difference only; the body must match — checked below
    if stale2.split("requires ")[1] != stale.split("requires ")[1]:
        print("FAIL-CLOSED: stale roundtrip nondeterminism (body)")
        return 1
    if flip2.split("requires ")[1] != flipped.split("requires ")[1]:
        print("FAIL-CLOSED: flip roundtrip nondeterminism (body)")
        return 1

    OUT.mkdir(parents=True, exist_ok=True)
    p1 = OUT / "abs-machine-mut-stale.k"
    p2 = OUT / "abs-machine-mut-flip.k"
    p1.write_text(header_for("STALE-TAG", "SRW3N-ABS-TDR-MUT-STALE", src_sha,
                             "THE RE-TAG IS FORGOTTEN: init-accept keeps tag 0 with the initialized fields.")
                  + stale)
    p2.write_text(header_for("TAG-FLIP", "SRW3N-ABS-TDR-MUT-FLIP", src_sha,
                             "EVERY STEP-ROW RHS TAG LITERAL IS FLIPPED (0<->1); the incoherent row is untouched.")
                  + flipped)
    print(f"src sha256(abs-machine-tdr.k) = {src_sha}")
    print(f"wrote {p1.relative_to(REPO)} sha256={hashlib.sha256(p1.read_bytes()).hexdigest()}")
    print(f"wrote {p2.relative_to(REPO)} sha256={hashlib.sha256(p2.read_bytes()).hexdigest()}")
    print(f"flip census = {counts} (expect 1->0: {expect_1_to_0}, 0->1: {expect_0_to_1})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
