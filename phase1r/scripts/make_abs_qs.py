#!/usr/bin/env python3
"""SRW3 Phase 1R — the additive stall-row variant generator (make_abs_qs.py).

Emits phase1r/semantics/abs-machine-qs.k: module SRW3N-ABS-QS, which
IMPORTS the frozen 1Q machine of record (SRW3N-ABS-Q) unchanged and adds
EXACTLY FOUR runner rows — the explicit pre-init stall rows:

    for each ground exec shape aExecJ(A1,A2):
      <k> aExecJ(A1,A2) => .K </k>
      <absjshadow> absStQ(0,false,false,G,E,N,SF,D)
                => absStQ(0,false,false,G,E,N,SF,D) </absjshadow>

WHY (the 1R diagnosis, spec/fold-decomposition.md §3 F2'): on the 1Q
machine these four cells are covered by the [owise] runner complement,
whose branch condition is a NEGATION — it never refines the command
variable — so in a symbolic run the executable side condition
absExecutableQ(cons(AC, R), state) stays stuck on AC and the circular
axiom cannot re-apply: the pre-init stall chain explores without bound
(the TAG0/T0F/COMPOSED timeouts).  Making the stall cells explicit
REFINES the branch (the command becomes concrete) so the requires
EVALUATES — and because absExecutableQ's exec row returns false at tag 0,
the refined branch is killed by its own requires (exactly the domain
predicate's stall discipline: pre-init exec commands are not executed
transitions).

SEMANTICS-PRESERVATION ARGUMENT (disclosed; the machine of record is
NOT modified): on every (command, state) cell the variant's transition
is the 1Q machine's transition.  For the four added cells the [owise]
complement on the 1Q machine already produces the identical result
(command consumed; shadow state unchanged) — the added rows only make
the same transitions explicit; every other cell is matched by the same
1Q rows.  The relation is therefore UNCHANGED; the claims over QS are
claims over the 1Q abstract machine.  The mechanical evidence battery:
1R-QS-RUN-HONEST-Q, 1R-QS-RUN-INIT-EXEC-Q (the 1Q ground executions,
restated over QS), 1R-QS-STALL-STEP-Q (the stall identity at the runner),
1R-QS-STALL-NONEXEC-Q (the stall run is non-executable), and the 1Q
strong empty-commit reject step (re-run over QS).

Fail-closed checks (every run):
  S1  the frozen 1Q machine sha256 anchor;
  S2  the exec command syntax present (2 AOk x 2 ASrc = 4 shapes);
  S3  the emitted module carries exactly 4 stall rules, each with an
      IDENTITY shadow RHS, and NO other rule;
  S4  roundtrip determinism (byte-identical regeneration).

The generator NEVER writes outside phase1r/.  Level III only; no
consensus-integration claim.
"""
import hashlib
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
PHASE = HERE.parent
REPO = PHASE.parent
SRC_1Q = REPO / "phase1q" / "semantics" / "abs-machine-q.k"
SHA_1Q = "2e938fcb8939e0efe15e554687947b4dc44ece9a6a843f293799a18204e5383f"
OUT = PHASE / "semantics" / "abs-machine-qs.k"

EXEC_SHAPES = [
    "aExecJ(A1:AOk, A2:ASrc)",  # the four ground shapes, taken symbolically
                                # over A1 x A2 (the runner refines per fork)
]


def fail(msg):
    print("MAKE-ABS-QS FAIL-CLOSED: " + msg)
    sys.exit(1)


def emit() -> str:
    hdr = f"""// =============================================================================
// SRW3 PHASE 1R — THE ADDITIVE STALL-ROW VARIANT (GENERATED — DO NOT EDIT)
//                    (phase1r/semantics/abs-machine-qs.k)
//
// GENERATED by phase1r/scripts/make_abs_qs.py from the FROZEN 1Q machine
// of record (sha256 {SHA_1Q}).  Regenerate; never edit.
//
// SRW3N-ABS-QS = SRW3N-ABS-Q (imported UNCHANGED) + the four explicit
// pre-init stall rows (edit set ER-1).  SEMANTICS-PRESERVING by
// construction: on the added cells the 1Q [owise] complement already
// produces the identical transition (command consumed; shadow unchanged);
// the added rows only REFINE the branch conditions (a concrete command
// head where the owise kept a negated variable) so that the executable
// side conditions of the decomposition claims EVALUATE.  The transition
// relation is UNCHANGED; claims over QS are claims over the 1Q machine.
// Evidence battery: 1R-QS-RUN-HONEST-Q, 1R-QS-RUN-INIT-EXEC-Q,
// 1R-QS-STALL-STEP-Q, 1R-QS-STALL-NONEXEC-Q (proofs/n_r_qs_battery.k),
// and the 1Q strong empty-commit reject step re-run over QS.
// Level III only; no consensus-integration claim.
// =============================================================================

requires "../../phase1q/semantics/abs-machine-q.k"

module SRW3N-ABS-QS
  imports SRW3N-ABS-Q

  // ===========================================================================
  // ER-1 — THE EXPLICIT PRE-INIT STALL ROWS (the [owise] complement's
  //        (exec, tag-0) cells, made explicit; RHS = the owise's identity).
  //        One rule per exec shape; the state pattern is the GENERAL
  //        tag-0 state (the owise's coverage on the coherent fragment).
  // ===========================================================================
"""
    rows = []
    for shape in EXEC_SHAPES:
        rows.append(f"""  rule <k> {shape} => .K ... </k>
       <absjshadow> absStQ(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag)
                 => absStQ(0, false, false, G, E, N, SF, D) </absjshadow>

""")
    tail = """endmodule
"""
    return hdr + "".join(rows) + tail


def main():
    # S1 — the frozen anchor
    if not SRC_1Q.is_file():
        fail(f"missing the 1Q machine of record: {SRC_1Q}")
    digest = hashlib.sha256(SRC_1Q.read_bytes()).hexdigest()
    if digest != SHA_1Q:
        fail(f"1Q machine sha256 {digest} != the anchor — refusing to generate")
    print("S1 OK    1Q machine of record sha256 anchored")

    # S2 — the exec command syntax
    text = SRC_1Q.read_text()
    for tok in ("| aExecJ ( AOk , ASrc )", "syntax AOk ::= \"aOkT\" | \"aOkF\"",
                "| \"aSrcOther\""):
        if tok not in text:
            fail(f"the exec command syntax drifted; expected: {tok}")
    print("S2 OK    exec command syntax verified (2 AOk x 2 ASrc)")

    # S3/S4 — emit + structural checks + roundtrip
    out1 = emit()
    out2 = emit()
    if out1 != out2:
        fail("the generator is not deterministic (roundtrip mismatch)")
    n_rules = out1.count("\n  rule <k>")
    if n_rules != 1:  # one templated rule symbolically covering the 4 shapes
        fail(f"the emitted module carries {n_rules} stall rules; expected 1 "
             f"(symbolic over A1 x A2 — the four ground shapes)")
    if out1.count("=> absStQ(0, false, false, G, E, N, SF, D) </absjshadow>") != 1:
        fail("the stall rule's shadow RHS is not the identity")
    OUT.write_text(out1)
    print(f"S3 OK    exactly one stall rule (identity RHS; symbolic A1 x A2)")
    print(f"S4 OK    roundtrip deterministic ({len(out1)} bytes)")
    print(f"WROTE {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
