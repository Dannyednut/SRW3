#!/usr/bin/env python3
"""SRW3 Phase 1O — compose the WEAK+R machine (the soundness control).

abs-machine-weak-r.k = the frozen 1N abstract machine + the TWO disclosed
1O edits: (1) the WEAK accept-commit (the presented bit carried — the
make_abs_weak.py edit; the K port of the 1N Python S4 control) and (2) the
REWRITE-DISPATCHED runner (the make_abs_r.py edit — 12 ground-command
runner rules + the [owise] complement).  The universal machine-form claim
over THIS definition MUST FAIL: the R runner genuinely evaluates the weak
accept on the ground unsafe-commit shape and breaks ABSInv.

Fail-closed: both edit blocks must be found exactly once; the emitted
module body is verified against the two generators' blocks.

Usage: python3 phase1o/scripts/make_abs_weak_r.py
"""
import hashlib
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parents[1]
REPO = HERE.parent
SRC = REPO / "phase1n" / "semantics" / "abs-machine.k"
RFILE = HERE / "semantics" / "abs-machine-r.k"
DST = HERE / "semantics" / "abs-machine-weak-r.k"

OLD_RULE = """  rule absStepJ(absSt(true, true, G:Int, E:Int, N:Int, _:Bool, D:ADiag),
                aCommitJ(aOkT, aOkT))
    => absSt(true, true, G -Int 1, E -Int 1, N +Int 1, true, D)
    requires G >=Int 1 andBool E >=Int 1
"""
NEW_RULE = """  rule absStepJ(absSt(true, true, G:Int, E:Int, N:Int, _:Bool, D:ADiag),
                aCommitJ(aOkT, B2:AOk))
    => absSt(true, true, G -Int 1, E -Int 1, N +Int 1, B2 ==K aOkT, D)
    requires G >=Int 1 andBool E >=Int 1
"""
OLD_BLOCK = """  // ---- the abstract runner (the <absjshadow> machine) -------------------
  rule <k> aConsJ(AC:ACmd, R:APProg) => AC ~> R ... </k>
  rule <k> aRunNilJ => .K ... </k>

  rule <k> aInitJ(AB:AOk) => .K ... </k>
       <absjshadow> AX:AState => absStepJ(AX, aInitJ(AB:AOk)) </absjshadow>

  rule <k> aExecJ(AB:AOk, AS:ASrc) => .K ... </k>
       <absjshadow> AX:AState => absStepJ(AX, aExecJ(AB:AOk, AS:ASrc)) </absjshadow>
    requires absCfgPinnedOf(AX) andBool absCatPinnedOf(AX)
  // NO rule for aExecJ on an unpinned shadow: the declared stall class,
  // mirroring the concrete machine (the pExecJ dispatch requires the pins).

  rule <k> aGateJ(AB:AOk) => .K ... </k>
       <absjshadow> AX:AState => absStepJ(AX, aGateJ(AB:AOk)) </absjshadow>

  rule <k> aCommitJ(AB1:AOk, AB2:AOk) => .K ... </k>
       <absjshadow> AX:AState => absStepJ(AX, aCommitJ(AB1:AOk, AB2:AOk)) </absjshadow>
"""

HEADER = """// =============================================================================
// SRW3 PHASE 1O — THE WEAK+R MACHINE (the soundness control definition)
//                    (phase1o/semantics/abs-machine-weak-r.k)
//
// GENERATED by composing the two disclosed 1O edits on the frozen 1N
// abstract machine: the WEAK accept-commit (the presented bit carried —
// the make_abs_weak.py edit) + the REWRITE-DISPATCHED runner (the
// make_abs_r.py edit).  The universal machine-form claim over THIS
// definition MUST FAIL (the ground unsafe-commit run genuinely evaluates
// and breaks ABSInv).  DO NOT EDIT BY HAND.  Level III only.
// =============================================================================

"""

def main() -> int:
    src = SRC.read_text()
    if src.count(OLD_RULE) != 1 or OLD_RULE not in src:
        print("FAIL-CLOSED: weak-edit block not found exactly once"); return 1
    out = src.replace(OLD_RULE, NEW_RULE)
    r_file = RFILE.read_text()
    i0 = r_file.find("// PHASE 1O DISCLOSED R EDIT")
    i1 = r_file.find("  // ===========================================================================", i0)
    if i0 < 0 or i1 < 0:
        print("FAIL-CLOSED: R block not found in abs-machine-r.k"); return 1
    R_BLOCK = r_file[i0:i1]
    if out.count(OLD_BLOCK) != 1:
        print("FAIL-CLOSED: runner block not found exactly once"); return 1
    out = out.replace(OLD_BLOCK, "  // ---- the abstract runner (the <absjshadow> machine) -------------------\n" + R_BLOCK)
    out = out.replace("module SRW3N-ABS\n", "module SRW3N-ABS-WEAK-R\n")
    req = out.find('requires "srw3closure-j-m4.k"')
    if req < 0:
        print("FAIL-CLOSED: requires line not found"); return 1
    out = HEADER + out[req:]
    DST.write_text(out)
    print("wrote abs-machine-weak-r.k")
    print("sha256:", hashlib.sha256(DST.read_bytes()).hexdigest())
    return 0

if __name__ == "__main__":
    sys.exit(main())
