#!/usr/bin/env python3
"""SRW3 Phase 1O — derive the WEAK abstract machine (the K-level soundness
control for the machine-form universal theorem).

WEAK = the 1N Python mirror's S4 control, ported to the K definition:
the accept-commit carries the PRESENTED second bit (B2 ==K aOkT) instead
of the COMPUTED-safe literal `true`.  Under the weak machine the ground
run [init-accept, exec-mint, gate-mint, commit(aOkT,aOkF)] ends at
absSt(true,true,0,0,1,false,adNone) — ABSInv FALSE — so the universal
machine-form claim MUST FAIL over the weak definition.  If it closes,
the real machine's proof is insensitive to the guard and is therefore
unsound as a universal-theorem proof (the stutter-artifact hazard).

Discipline (the make_m2/make_m3/make_m4 rule): the derived file differs
from abs-machine.k by EXACTLY the disclosed edits and NOTHING else —
verified by a line-diff check that fails closed.

Usage: python3 phase1o/scripts/make_abs_weak.py
Outputs: phase1o/semantics/abs-machine-weak.k  (module SRW3N-ABS-WEAK)
"""
import difflib
import hashlib
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parents[1]
REPO = HERE.parent
SRC = REPO / "phase1n" / "semantics" / "abs-machine.k"
DST = HERE / "semantics" / "abs-machine-weak.k"

OLD_RULE = """  rule absStepJ(absSt(true, true, G:Int, E:Int, N:Int, _:Bool, D:ADiag),
                aCommitJ(aOkT, aOkT))
    => absSt(true, true, G -Int 1, E -Int 1, N +Int 1, true, D)
    requires G >=Int 1 andBool E >=Int 1
"""

NEW_RULE = """  // PHASE 1O DISCLOSED WEAK EDIT (the ONLY SRW3N-ABS -> SRW3N-ABS-WEAK
  // rule difference): the accept-commit carries the PRESENTED second bit
  // (B2 ==K aOkT) instead of the COMPUTED-safe literal `true` — the K port
  // of the 1N Python mirror's S4 weak control.  The universal machine-form
  // claim MUST FAIL over this definition (the ground run [init-accept,
  // exec-mint, gate-mint, commit(aOkT,aOkF)] breaks ABSInv at the final
  // state).  A proof of that claim here would mean the real machine's
  // proof is guard-insensitive and unsound.
  rule absStepJ(absSt(true, true, G:Int, E:Int, N:Int, _:Bool, D:ADiag),
                aCommitJ(aOkT, B2:AOk))
    => absSt(true, true, G -Int 1, E -Int 1, N +Int 1, B2 ==K aOkT, D)
    requires G >=Int 1 andBool E >=Int 1
"""

OLD_MODULE = "module SRW3N-ABS\n"
NEW_MODULE = "module SRW3N-ABS-WEAK\n"

HEADER = """// =============================================================================
// SRW3 PHASE 1O — THE WEAK ABSTRACT MACHINE (the soundness control)
//                    (phase1o/semantics/abs-machine-weak.k)
//
// GENERATED by phase1o/scripts/make_abs_weak.py from phase1n/semantics/
// abs-machine.k.  DO NOT EDIT BY HAND.  The ONLY rule difference is the
// disclosed weak accept-commit below; the module is renamed SRW3N-ABS-WEAK.
// Level III only; no consensus-integration claim.
// =============================================================================

"""

def main() -> int:
    src = SRC.read_text()
    if src.count(OLD_RULE) != 1:
        print("FAIL-CLOSED: the accept-commit rule block not found exactly once")
        return 1
    out = src.replace(OLD_RULE, NEW_RULE)
    if out.count(OLD_MODULE) != 1:
        print("FAIL-CLOSED: module declaration not found exactly once")
        return 1
    out = out.replace(OLD_MODULE, NEW_MODULE)
    # strip the original top header comment (through the first end-of-comment)
    idx = out.find("module SRW3N-ABS-WEAK")
    # remove everything up to the requires line, then rebuild with the new header
    req_idx = out.find('requires "srw3closure-j-m4.k"')
    if req_idx < 0:
        print("FAIL-CLOSED: requires line not found")
        return 1
    out = HEADER + out[req_idx:]
    DST.write_text(out)

    # ---- roundtrip verification: the diff must be EXACTLY the disclosure --
    a = SRC.read_text().splitlines()
    b = DST.read_text().splitlines()
    diff = list(difflib.unified_diff(a, b, lineterm=""))
    removed = [l[1:] for l in diff if l.startswith("-") and not l.startswith("---")]
    added = [l[1:] for l in diff if l.startswith("+") and not l.startswith("+++")]
    # ---- roundtrip verification: diff the module BODIES (below the module
    # declaration).  The body diff must be EXACTLY: the renamed module line +
    # the accept-commit rule block (4 lines).  Nothing else may move.
    def body(lines, marker):
        i = next(k for k, l in enumerate(lines) if l.startswith(marker))
        return lines[i:]
    ba = body(a, "module SRW3N-ABS")
    bb = body(b, "module SRW3N-ABS-WEAK")
    bdiff = list(difflib.unified_diff(ba, bb, lineterm=""))
    brem = [l[1:] for l in bdiff if l.startswith("-") and not l.startswith("---")]
    badd = [l[1:] for l in bdiff if l.startswith("+") and not l.startswith("+++")]
    bctx = [l[1:] for l in bdiff if l.startswith(" ") and not l.startswith(" " * 3)]
    ok = (
        len(brem) == 3 and len(badd) >= 8
        and any("aCommitJ(aOkT, aOkT))" in l for l in brem)
        and any("true, D)" in l for l in brem)
        and any("aCommitJ(aOkT, B2:AOk))" in l for l in badd)
        and any("B2 ==K aOkT, D)" in l for l in badd)
        and any("PHASE 1O DISCLOSED WEAK EDIT" in l for l in badd)
        and not any("pInitJ" in l or "pExecJ" in l or "pGateEvalJ" in l
                    or "pCommitJ" in l or "ABSInv (" in l or "simJ (" in l
                    for l in brem + badd)
    )
    print(f"body-diff check: removed={len(brem)} added={len(badd)} (expect 3/8)")
    print(f"weak-derivation ok={ok}  removed={len(removed)} added={len(added)}")
    print(f"sha256 abs-machine.k     : {hashlib.sha256(SRC.read_bytes()).hexdigest()}")
    print(f"sha256 abs-machine-weak.k: {hashlib.sha256(DST.read_bytes()).hexdigest()}")
    return 0 if ok else 1

if __name__ == "__main__":
    sys.exit(main())
