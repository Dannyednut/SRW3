#!/usr/bin/env python3
"""SRW3 Phase 1O — generate the LEMMA module for the machine-form universal.

The universal's stuck obligation (the R-variant residual of record) is the
implication check `ABSInv(absStepJ(state, ground-cmd))` over a symbolic
state constrained only by the ABSInv disjunction: the step equations match
by PATTERN and need the branch literals IN the matching, which the checker
does not derive from the disjunctive constraint store (the R4/R10 evidence
at toy scale; the 1O-UNIV-MACHINE-R residual on the real machine).

The principled K answer: the branch-complete preservation content enters
the composition proof as [lemma] axioms — the 1N ABS-PRESV-* family
(24 Bool-form claims = every ground command shape x every ABSInv branch,
over ALL field valuations), each of which is INDEPENDENTLY PROVEN with a
retained log (1N bundle) and re-proven in the 1O bundle before use.

This script EXTRACTS the PRESV claim blocks from the frozen 1N proof file
byte-exactly and emits them with the [lemma] attribute added.  The
fail-closed check: every extracted claim text must be byte-identical to
its 1N original except the attribute line.

Usage: python3 phase1o/scripts/make_o_lemmas.py
Output: phase1o/proofs/n_o_lemmas.k  (module O-LEMMAS, imports SRW3N-ABS-R)
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parents[1]
REPO = HERE.parent
SRC = REPO / "phase1n" / "proofs" / "n_abs_proofs.k"
DST = HERE / "proofs" / "n_o_lemmas.k"

def main() -> int:
    lines = SRC.read_text().splitlines()
    claims = []          # (label, [lines])
    cur = None
    for ln in lines:
        m = re.search(r"label\((ABS-PRESV-[A-Z0-9-]+)\)", ln)
        if m and cur is not None:
            cur[1].append(ln)
            claims.append(cur)
            cur = None
            continue
        if m:
            print(f"WARN: label without opening claim: {m.group(1)}")
            continue
        if ln.strip().startswith("claim"):
            cur = (None, [ln])
        elif cur is not None:
            cur[1].append(ln)
            if ln.strip() == "" and len(cur[1]) > 1:
                # blank line: check if a label was seen
                text = "\n".join(cur[1])
                m2 = re.search(r"label\((ABS-PRESV-[A-Z0-9-]+)\)", text)
                if m2:
                    claims.append((m2.group(1), cur[1]))
                cur = None
    # The simple scanner above is brittle; do a robust block scan instead:
    text = SRC.read_text()
    blocks = re.findall(r"(claim\s*(?://[^\n]*\n)*\s*(?:<[^>]+>|[^\[\]])*?\[label\((ABS-PRESV-[A-Z0-9-]+)\)\])", text)
    found = {}
    for blk, lab in blocks:
        found[lab] = blk.rstrip()
    print(f"extracted {len(found)} ABS-PRESV-* claim blocks")
    expected_prefixes = ("ABS-PRESV-I-", "ABS-PRESV-P-")
    bad = [k for k in found if not k.startswith(expected_prefixes)]
    if bad:
        print("FAIL-CLOSED: unexpected labels", bad)
        return 1
    if len(found) < 20:
        print("FAIL-CLOSED: too few PRESV claims extracted (branch-complete family expected)")
        return 1

    out = []
    out.append("// =============================================================================")
    out.append("// SRW3 PHASE 1O — THE LEMMA MODULE (the branch-complete preservation family")
    out.append("//                    as TRUSTED axioms for the machine-form universal)")
    out.append("//                    (phase1o/proofs/n_o_lemmas.k — GENERATED by")
    out.append("//                     scripts/make_o_lemmas.py — DO NOT EDIT BY HAND)")
    out.append("//")
    out.append("// Every claim below is BYTE-IDENTICAL to its ABS-PRESV-* original in the")
    out.append("// frozen 1N proof file (phase1n/proofs/n_abs_proofs.k).  K v7.1.337 has")
    out.append("// no [lemma] claim attribute; the trusted-axiom mechanism is the kprove")
    out.append("// flag:  kprove ... --claims 1O-UNIV-MACHINE-RL --trusted <PRESV labels>.")
    out.append("// Trust discipline: every trusted claim is INDEPENDENTLY PROVEN first —")
    out.append("// the 1N bundle retains the original logs, and the 1O runner re-proves")
    out.append("// every lemma claim in this module BEFORE the universal is attempted")
    out.append("// (run_o_univ.sh order), with raw logs retained under phase1o/transcripts/k/.")
    out.append("// Level III only; no consensus-integration claim.")
    out.append("// =============================================================================")
    out.append("")
    out.append('requires "../semantics/abs-machine-r.k"')
    out.append("")
    out.append("module O-LEMMAS")
    out.append("  imports SRW3N-ABS-R")
    out.append("")
    for lab in sorted(found):
        blk = found[lab]
        # add `lemma` to the attribute line
        m = re.search(r"\[label\(" + lab + r"\)\]", blk)
        if not m:
            print(f"FAIL-CLOSED: attribute not found for {lab}")
            return 1
        blk = blk.replace(f"[label({lab})]", f"[label({lab})]")  # text kept byte-identical
        out.append(blk)
        out.append("")
    out.append("  // ===========================================================================")
    out.append("  // 1O-UNIV-MACHINE-RL — the machine-form universal over the R machine,")
    out.append("  //     with the branch-complete preservation family above as [lemma]")
    out.append("  //     axioms.  The per-step content comes from the lemmas (each")
    out.append("  //     independently proven); the composition comes from the")
    out.append("  //     circularity; the [owise] complement rule closes the prover's")
    out.append("  //     spurious complement branch.  The soundness controls: the")
    out.append("  //     weak-machine universal (n_o_univ_weak_r.k) MUST FAIL and the")
    out.append("  //     destination control MUST FAIL.")
    out.append("  // ===========================================================================")
    out.append("  claim")
    out.append("    <srw3closureJ>")
    out.append("      <k> RUN:APProg => .K ... </k>")
    out.append("      <absjshadow> AX:AState => ?AX2:AState </absjshadow>")
    out.append("      ...")
    out.append("    </srw3closureJ>")
    out.append("    requires ABSInv(AX) andBool absExecutable(RUN:APProg, AX:AState)")
    out.append("    ensures ABSInv(?AX2:AState)")
    out.append("    [circularity, label(1O-UNIV-MACHINE-RL)]")
    out.append("")
    out.append("  claim")
    out.append("    <srw3closureJ>")
    out.append("      <k> RUN:APProg => .K ... </k>")
    out.append("      <absjshadow> AX:AState => ?AX2:AState </absjshadow>")
    out.append("      ...")
    out.append("    </srw3closureJ>")
    out.append("    requires ABSInv(AX) andBool absCfgPinnedOf(AX)")
    out.append("         andBool absExecutable(RUN:APProg, AX:AState)")
    out.append("    ensures absInitShaped(?AX2:AState)")
    out.append("    [circularity, label(1O-UNIV-PREFIX-RL)]")
    out.append("")
    out.append("  claim")
    out.append("    <srw3closureJ>")
    out.append("      <k> RUN:APProg => .K ... </k>")
    out.append("      <absjshadow> AX:AState => ?AX2:AState </absjshadow>")
    out.append("      ...")
    out.append("    </srw3closureJ>")
    out.append("    requires ABSInv(AX) andBool absExecutable(RUN:APProg, AX:AState)")
    out.append("    ensures ?AX2:AState ==K absGenesis")
    out.append("    [label(1O-NEG-DEST-RL)]")
    out.append("")
    out.append("endmodule")
    DST.write_text("\n".join(out) + "\n")
    print(f"wrote {DST} with {len(found)} [lemma] claims")
    return 0

if __name__ == "__main__":
    sys.exit(main())
