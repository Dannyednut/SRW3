OUTK = REPO / "phase1s" / "proofs" / "n_s_coverage.k"
OUTC = REPO / "phase1s" / "audit" / "coverage-table-1s.csv"

ANCHORS = {
    "1Q_MACHINE": ("2e938fcb8939e0efe15e554687947b4dc44ece9a6a843f293799a18204e5383f", Q),
    "1R_QS": ("b526e2997e8f3f0d54fbb0a76ef0e1d718fae9afcffd6610bf383fb99cd3bbec", QS),
}

# the 17 declared step-row heads of record (spec/transition-coverage.md §2),
# as regex fragments that MUST appear in the frozen source.
STEP_HEADS = [
    ("1", "init-accept", r"absStQ\(0, false, false, _:PoolCount, _:PoolCount, _:Int, _:Bool, D:ADiag\),\s*\n\s*aInitJ\(aOkT\)"),
    ("2", "init-refuse", r"absStQ\(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag\),\s*\n\s*aInitJ\(aOkF\)"),
    ("3", "re-init", r"absStQ\(1, true, true, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag\),\s*\n\s*aInitJ\(_:AOk\)"),
    ("4", "stall", r"absStQ\(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag\),\s*\n\s*aExecJ\(_:AOk, _:ASrc\)"),
    ("5", "exec-mint", r"aExecJ\(aOkT, aSrcAuth\)\)\s*\n\s*=> absStQ\(1, true, true, G, succP\(E\)"),
    ("6", "exec-src-refuse", r"aExecJ\(aOkT, aSrcOther\)"),
    ("7", "exec-unsup", r"aExecJ\(aOkF, _:ASrc\)"),
    ("8", "gate-pre", r"absStQ\(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag\),\s*\n\s*aGateJ\(_:AOk\)"),
    ("9", "gate-empty", r"absStQ\(1, true, true, G:PoolCount, zeroP, N:Int, SF:Bool, _:ADiag\),\s*\n\s*aGateJ\(_:AOk\)"),
    ("10", "gate-mint", r"absStQ\(1, true, true, G:PoolCount, succP\(E0\), N:Int, SF:Bool, D:ADiag\),\s*\n\s*aGateJ\(aOkT\)"),
    ("11", "gate-refuse", r"absStQ\(1, true, true, G:PoolCount, succP\(E0\), N:Int, SF:Bool, _:ADiag\),\s*\n\s*aGateJ\(aOkF\)"),
    ("12", "commit-pre", r"absStQ\(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag\),\s*\n\s*aCommitJ\(_:AOk, _:AOk\)"),
    ("13", "commit-accept", r"absStQ\(1, true, true, succP\(G0\), succP\(E0\), N:Int, _:Bool, D:ADiag\),\s*\n\s*aCommitJ\(aOkT, aOkT\)"),
    ("14", "commit-C", r"aCommitJ\(aOkT, aOkF\)"),
    ("15", "commit-D", r"aCommitJ\(aOkF, _:AOk\)"),
    ("16", "commit-G-empty", r"absStQ\(1, true, true, zeroP, E:PoolCount, N:Int, SF:Bool, D:ADiag\),\s*\n\s*aCommitJ\(_:AOk, _:AOk\)"),
    ("17", "commit-E-empty", r"absStQ\(1, true, true, succP\(G0\), zeroP, N:Int, SF:Bool, D:ADiag\),\s*\n\s*aCommitJ\(_:AOk, _:AOk\)"),
]

HEADER = '''// =============================================================================
// SRW3 PHASE 1S — THE TRANSITION-COVERAGE BATTERY (GENERATED — DO NOT EDIT)
//                    (phase1s/proofs/n_s_coverage.k)
//
// GENERATED by phase1s/scripts/make_coverage_1s.py from the FROZEN QS
// machine source (sha256 anchored; the rule inventory checked fail-closed).
// Regenerate; never edit. Spec: spec/transition-coverage.md.
// Every claim is a ground cell of the declared partition (the documented
// post-state), a guard-grid point of the mirror's requires-split, an
// exclusivity pair, a complement-inertness cell, or an executable-domain
// anchor. Whatever the raw results, they are recorded and never relabeled.
// Level III only; no consensus-integration claim.
// =============================================================================

requires "../semantics/rel-machine.k"

module S-COVERAGE-PROOFS
  imports SRW3N-REL-S

'''

FOOTER = 'endmodule\n'


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def claim(label: str, body: str, comment: str = "") -> str:
    head = f"  // {comment}\n" if comment else ""
    return f"{head}  claim <k> {body} </k>\n    [label({label})]\n\n"


def main() -> int:
    for name, (expected, path) in ANCHORS.items():
        got = sha256(path)
        if got != expected:
            print(f"C-CHECK FAILED {name}: {got} != {expected}")
            return 1
        print(f"C-ANCHOR OK {name}: {got[:16]}…")

    src = QS.read_text()

    # C1: the rule-inventory counts (the step rows live in the 1Q file;
    # the QS variant adds exactly ONE shadow row — the explicit stall)
    q_src = Q.read_text()
    step_rules = re.findall(r"rule absStepQ\(", q_src)
    if len(step_rules) != 18:
        print(f"C1 FAILED: absStepQ rule heads = {len(step_rules)}, expected 18")
        return 1
    print(f"C1 OK    absStepQ rule heads: {len(step_rules)} = 17 declared + 1 [owise]")
    fork_rows = len(re.findall(r"<absjshadow>", q_src))
    qs_rows = len(re.findall(r"<absjshadow>", src))
    if fork_rows != 36 or qs_rows != 1:
        print(f"C1 FAILED: shadow rows 1Q={fork_rows} (expected 36: 8 tag-0 + 6 tag-1 + 20 fork + 1 aRunNilJ-cell + 1 complement), QS={qs_rows} (expected 1: the explicit stall row)")
        return 1
    print(f"C1 OK    shadow rows: 1Q={fork_rows} + QS={qs_rows} (the QS delta is the explicit stall row)")

    # C2: every declared head appears verbatim (in the 1Q source — the
    # step rows live there; the QS variant is the additive stall variant)
    table = ["cell_id,class,head_found_in_frozen_source"]
    for cid, cls, pat in STEP_HEADS:
        if not (re.search(pat, src) or re.search(pat, q_src)):
            print(f"C2 FAILED: declared head {cid} ({cls}) not found in the frozen source")
            return 1
        table.append(f"{cid},{cls},yes")
    print(f"C2 OK    all {len(STEP_HEADS)} declared heads found verbatim in the frozen source")

    # C3: the battery
    b = []
    # ---- the 17 declared cells (ground evaluation of the documented post) ----
    b.append("  // ==== the declared cells (ground evaluation; spec §2 table) ====\n\n")
    b.append(claim("1S-COV-Q-INIT-ACCEPT",
                   "absStepQ(absStQ(0, false, false, zeroP, zeroP, 0, false, adNone), aInitJ(aOkT)) => absStQ(1, true, true, zeroP, zeroP, 0, true, adNone)",
                   "cell 1: the ONLY legal re-tag (0->1); pools reset"))
    b.append(claim("1S-COV-Q-INIT-REFUSE",
                   "absStepQ(absStQ(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag), aInitJ(aOkF)) => absStQ(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag)",
                   "cell 2: refuse, tag kept"))
    b.append(claim("1S-COV-Q-REINIT",
                   "absStepQ(absStQ(1, true, true, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag), aInitJ(aOkT)) => absStQ(1, true, true, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag)",
                   "cell 3: re-init refused"))
    b.append(claim("1S-COV-Q-STALL",
                   "absStepQ(absStQ(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag), aExecJ(aOkT, aSrcAuth)) => absStQ(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag)",
                   "cell 4: the explicit pre-init stall (identity; QS ER-1 row)"))
    b.append(claim("1S-COV-Q-EXE-MINT",
                   "absStepQ(absStQ(1, true, true, G:PoolCount, succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag), aExecJ(aOkT, aSrcAuth)) => absStQ(1, true, true, G:PoolCount, succP(succP(E0:PoolCount)), N:Int, SF:Bool, D:ADiag)",
                   "cell 5: the mint class (structural inc)"))
    b.append(claim("1S-COV-Q-EXE-SRC",
                   "absStepQ(absStQ(1, true, true, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag), aExecJ(aOkT, aSrcOther)) => absStQ(1, true, true, G:PoolCount, E:PoolCount, N:Int, SF:Bool, adSource)",
                   "cell 6: J-A08 refusal"))
    b.append(claim("1S-COV-Q-EXE-UNSUP",
                   "absStepQ(absStQ(1, true, true, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag), aExecJ(aOkF, aSrcAuth)) => absStQ(1, true, true, G:PoolCount, E:PoolCount, N:Int, SF:Bool, adExecRefuse)",
                   "cell 7: unsupported/bounds"))
    b.append(claim("1S-COV-Q-GATE-PRE",
                   "absStepQ(absStQ(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag), aGateJ(aOkT)) => absStQ(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, adGate)",
                   "cell 8: pre-init refusal"))
    b.append(claim("1S-COV-Q-GATE-EMPTY",
                   "absStepQ(absStQ(1, true, true, G:PoolCount, zeroP, N:Int, SF:Bool, D:ADiag), aGateJ(aOkT)) => absStQ(1, true, true, G:PoolCount, zeroP, N:Int, SF:Bool, adGate)",
                   "cell 9: row A-Z (empty pool, any bit)"))
    b.append(claim("1S-COV-Q-GATE-MINT",
                   "absStepQ(absStQ(1, true, true, G:PoolCount, succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag), aGateJ(aOkT)) => absStQ(1, true, true, succP(G:PoolCount), succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag)",
                   "cell 10: row B-S (the gate mint; E KEPT)"))
    b.append(claim("1S-COV-Q-GATE-REFUSE",
                   "absStepQ(absStQ(1, true, true, G:PoolCount, succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag), aGateJ(aOkF)) => absStQ(1, true, true, G:PoolCount, succP(E0:PoolCount), N:Int, SF:Bool, adGate)",
                   "cell 11: row C-S (refused, nonempty)"))
    b.append(claim("1S-COV-Q-COMMIT-PRE",
                   "absStepQ(absStQ(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag), aCommitJ(aOkT, aOkT)) => absStQ(0, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag)",
                   "cell 12: pre-init reject"))
    b.append(claim("1S-COV-Q-COMMIT-ACCEPT",
                   "absStepQ(absStQ(1, true, true, succP(G0:PoolCount), succP(E0:PoolCount), 7, false, D:ADiag), aCommitJ(aOkT, aOkT)) => absStQ(1, true, true, G0:PoolCount, E0:PoolCount, 8, true, D:ADiag)",
                   "cell 13: row B-SS (strip x2, N+1, safe=true — the SF input is overwritten)"))
    b.append(claim("1S-COV-Q-COMMIT-C",
                   "absStepQ(absStQ(1, true, true, succP(G0:PoolCount), succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag), aCommitJ(aOkT, aOkF)) => absStQ(1, true, true, succP(G0:PoolCount), succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag)",
                   "cell 14: row C-SS (reject, pools ok)"))
    b.append(claim("1S-COV-Q-COMMIT-D",
                   "absStepQ(absStQ(1, true, true, succP(G0:PoolCount), succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag), aCommitJ(aOkF, aOkT)) => absStQ(1, true, true, succP(G0:PoolCount), succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag)",
                   "cell 15: row D-SS (reject, pools ok)"))
    b.append(claim("1S-COV-Q-COMMIT-GEMPTY",
                   "absStepQ(absStQ(1, true, true, zeroP, succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag), aCommitJ(aOkT, aOkT)) => absStQ(1, true, true, zeroP, succP(E0:PoolCount), N:Int, SF:Bool, D:ADiag)",
                   "cell 16: row A-Z* (the G-empty complement)"))
    b.append(claim("1S-COV-Q-COMMIT-EEMPTY",
                   "absStepQ(absStQ(1, true, true, succP(G0:PoolCount), zeroP, N:Int, SF:Bool, D:ADiag), aCommitJ(aOkF, aOkF)) => absStQ(1, true, true, succP(G0:PoolCount), zeroP, N:Int, SF:Bool, D:ADiag)",
                   "cell 17: row A-SZ (the E-empty complement, G nonempty)"))
    # ---- the complement inertness (cell 18; four class representatives) ----
    b.append("  // ==== the [owise] complement: inert on incoherent tags only ====\n\n")
    for cmd in ["aInitJ(aOkT)", "aExecJ(aOkT, aSrcAuth)", "aGateJ(aOkF)", "aCommitJ(aOkT, aOkF)"]:
        lab = "1S-COV-Q-OWISE-INERT-" + re.sub(r"[^A-Za-z]", "", cmd)
        b.append(claim(lab,
                       f"absStepQ(absStQ(2, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag), {cmd}) => absStQ(2, false, false, G:PoolCount, E:PoolCount, N:Int, SF:Bool, D:ADiag)",
                       f"the incoherent-tag complement stutters on {cmd} (and TG=-1 by the >=2/<=-1 disjunct)"))

    # ---- the mirror guard-grid battery (the requires-split coverage) ----
    b.append("  // ==== the mirror guard-grid (absStepE requires-split coverage) ====\n\n")
    b.append(claim("1S-COV-E-GATE-A-AT0",
                   "absStepE(absStQE(true, true, 5, 0, 7, true, adNone), aGateJ(aOkT)) => absStQE(true, true, 5, 0, 7, true, adGate)",
                   "mirror gate row A fires at E'=0"))
    b.append(claim("1S-COV-E-GATE-A-ATNEG",
                   "absStepE(absStQE(true, true, 5, -3, 7, true, adNone), aGateJ(aOkF)) => absStQE(true, true, 5, -3, 7, true, adGate)",
                   "mirror gate row A fires at E'<0 (the Int model's own empty test)"))
    b.append(claim("1S-COV-E-GATE-B-AT1",
                   "absStepE(absStQE(true, true, 5, 1, 7, true, adNone), aGateJ(aOkT)) => absStQE(true, true, 6, 1, 7, true, adNone)",
                   "mirror gate row B fires at E'=1 (the exact boundary)"))
    b.append(claim("1S-COV-E-GATE-C-AT1",
                   "absStepE(absStQE(true, true, 5, 1, 7, true, adNone), aGateJ(aOkF)) => absStQE(true, true, 5, 1, 7, true, adGate)",
                   "mirror gate row C fires at E'=1"))
    b.append(claim("1S-COV-E-COMMIT-B-AT11",
                   "absStepE(absStQE(true, true, 1, 1, 7, false, adNone), aCommitJ(aOkT, aOkT)) => absStQE(true, true, 0, 0, 8, true, adNone)",
                   "mirror commit row B fires at (G',E')=(1,1) — the size-one boundary"))
    b.append(claim("1S-COV-E-COMMIT-A-AT0E",
                   "absStepE(absStQE(true, true, 0, 5, 7, true, adNone), aCommitJ(aOkT, aOkT)) => absStQE(true, true, 0, 5, 7, true, adNone)",
                   "mirror commit row A fires at G'=0"))
    b.append(claim("1S-COV-E-COMMIT-A-ATG0",
                   "absStepE(absStQE(true, true, 5, 0, 7, true, adNone), aCommitJ(aOkF, aOkT)) => absStQE(true, true, 5, 0, 7, true, adNone)",
                   "mirror commit row A fires at E'=0"))

    # ---- the exclusivity pairs (no unjustified overlap) ----
    b.append("  // ==== the exclusivity pairs (the requires-splits are disjoint) ====\n\n")
    b.append(claim("1S-COV-EXCL-GATE",
                   "(E:Int <=Int 0) andBool (E:Int >=Int 1) => false",
                   "gate rows A vs B/C: no E' satisfies both"))
    b.append(claim("1S-COV-EXCL-COMMIT",
                   "(G:Int >=Int 1) andBool (E:Int >=Int 1) andBool ((G:Int <=Int 0) orBool (E:Int <=Int 0)) => false",
                   "commit rows B/C/D vs A: no (G',E') satisfies both"))
    b.append(claim("1S-COV-EXCL-PREINIT",
                   "(0 ==Int 1) => false",
                   "the tag-0 rows and the tag-1 rows are branch-discriminated (the fork cover G5; the disjointness witness)"))

    # ---- the executable-domain anchors ----
    b.append("  // ==== the executable-domain anchors (the stall discipline) ====\n\n")
    b.append(claim("1S-COV-DOMAIN-PREEXEC",
                   "absExecutableQ(aConsJ(aExecJ(aOkT, aSrcAuth), aRunNilJ), absStQ(0, false, false, zeroP, zeroP, 0, false, adNone)) => false",
                   "a run whose head is a pre-init exec command is NOT executable"))
    b.append(claim("1S-COV-DOMAIN-NIL",
                   "absExecutableQ(aRunNilJ, absStQ(1, true, true, zeroP, zeroP, 0, true, adNone)) => true",
                   "the empty run is executable at any coherent state"))
    b.append(claim("1S-COV-DOMAIN-HONEST-PIPELINE",
                   "absExecutableQ(aConsJ(aInitJ(aOkT), aConsJ(aExecJ(aOkT, aSrcAuth), aRunNilJ)), absGenesisQ) => true",
                   "the honest pipeline (init then exec) is executable"))

    new = HEADER + "".join(b) + FOOTER
    csv = "\n".join(table) + "\n"

    if OUTK.exists():
        if OUTK.read_text() != new:
            print("C4 FAILED roundtrip mismatch on n_s_coverage.k")
            return 1
        print(f"C4 OK    roundtrip byte-identical ({len(new)} bytes)")
    else:
        OUTK.write_text(new)
        print(f"WROTE {OUTK} ({len(new)} bytes)")
    OUTC.write_text(csv)
    print(f"WROTE {OUTC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
