#!/usr/bin/env python3
# =============================================================================
# SRW3 Phase 1S — generator for the transition-coverage battery
#     (phase1s/scripts/make_coverage_1s.py -> phase1s/proofs/n_s_coverage.k
#                                         + phase1s/audit/coverage-table-1s.csv)
#
# SINGLE DETERMINISTIC SOURCE (mission §5): the battery is generated from
# the FROZEN QS machine source (pure reader — the file is never written).
# The generator:
#   C1  counts the absStepQ rule heads (expected 18 = 17 declared + 1
#       [owise]) and the runner fork rows (expected 4+16+9+2+1: the 1R G5
#       cover), failing closed on any mismatch;
#   C2  verifies each declared step row's head appears verbatim in the
#       frozen source (the 17-row inventory of spec/transition-coverage.md);
#   C3  emits the ground cell battery (one claim per declared cell), the
#       guard-grid battery for the mirror's requires-split rows, the
#       exclusivity pair claims, the complement-inertness claims, and the
#       executable-domain anchors;
#   C4  roundtrip: regenerating reproduces the battery byte-identically.
# A green generator run is an EXTERNAL check (TCB-2, disclosed) — it is
# NOT itself a mechanized theorem; every emitted claim is.
# Level III only; no consensus-integration claim.
# =============================================================================
