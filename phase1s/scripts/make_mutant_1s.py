#!/usr/bin/env python3
# =============================================================================
# SRW3 Phase 1S — generator for the OMIT mutant machine (mission §5, §7)
#     (phase1s/scripts/make_mutant_1s.py
#        -> phase1s/tests/abs-machine-mut-omit-gatemint-1s.k)
#
# The QS machine of record with EXACTLY ONE disclosed row omitted: the
# gate-mint row B-S (absStepQ, the E=succP(E0)/aOkT cell). The mutant is
# CONFINED to tests/ and is never imported by any of-record battery. The
# coverage battery's cell-10 claim, re-run against the mutant, must FAIL
# or hang (the step becomes stuck on that cell — the incoherent-tag
# complement cannot fire at tag 1): the omission is DETECTED.
#
# Fail-closed: M1 anchors the frozen sources; M2 checks the omitted row is
# present in the machine of record and absent exactly once in the mutant;
# M3 roundtrip.
# Level III only; no consensus-integration claim.
# =============================================================================
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
Q = REPO / "phase1q" / "semantics" / "abs-machine-q.k"
QS = REPO / "phase1r" / "semantics" / "abs-machine-qs.k"
OUT = REPO / "phase1s" / "tests" / "abs-machine-mut-omit-gatemint-1s.k"

ANCHORS = {
    "1Q_MACHINE": ("2e938fcb8939e0efe15e554687947b4dc44ece9a6a843f293799a18204e5383f", Q),
    "1R_QS": ("b526e2997e8f3f0d54fbb0a76ef0e1d718fae9afcffd6610bf383fb99cd3bbec", QS),
}

OMIT_MARK = "row B-S: the mint class (structural inc on G; E KEPT"

HEADER = '''// =============================================================================
// SRW3 PHASE 1S — THE OMIT MUTANT (GENERATED — DO NOT EDIT; NEGATIVE CONTROL)
//     (phase1s/tests/abs-machine-mut-omit-gatemint-1s.k)
//
// GENERATED by phase1s/scripts/make_mutant_1s.py. The QS machine of
// record with EXACTLY ONE disclosed omission: the gate-mint step row
// (absStepQ row B-S). CONFINED to tests/; never imported by any of-record
// battery. Purpose: the coverage battery's gate-mint cell claim must FAIL
// against this definition (the omission detector of record).
// Level III only; no consensus-integration claim.
// =============================================================================

'''


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    for name, (expected, path) in ANCHORS.items():
        got = sha256(path)
        if got != expected:
            print(f"M-CHECK FAILED {name}: {got} != {expected}")
            return 1
        print(f"M-ANCHOR OK {name}: {got[:16]}…")

    q_src = Q.read_text()
    qs_src = QS.read_text()

    # M2a: the row of record is present exactly once (its comment mark)
    if q_src.count(OMIT_MARK) != 1:
        print(f"M2 FAILED: the gate-mint row mark occurs {q_src.count(OMIT_MARK)}x in the 1Q source, expected 1")
        return 1
    print("M2 OK    the gate-mint row of record is present exactly once")

    # M2b: build the mutant = the 1Q source with that ONE rule deleted
    # (delete from the 'rule absStepQ(' line preceding the mark through the
    # end of that rule block), then re-apply the QS stall variant.
    lines = q_src.splitlines(keepends=True)
    mark_idx = next(i for i, l in enumerate(lines) if OMIT_MARK in l)
    start = next(i for i in range(mark_idx, -1, -1) if lines[i].startswith("  rule absStepQ("))
    end = next(i for i in range(mark_idx, len(lines)) if lines[i].strip() == "" or lines[i].startswith("  //") or lines[i].startswith("  rule ")) 
    if end <= start:
        print("M2 FAILED: could not bound the rule block")
        return 1
    mut_lines = lines[:start] + lines[end:]
    mut = "".join(mut_lines)
    if mut.count(OMIT_MARK) != 0:
        print("M2 FAILED: the omitted row still present in the mutant")
        return 1
    if mut.count("rule absStepQ(") != 17:
        print(f"M2 FAILED: mutant absStepQ heads = {mut.count('rule absStepQ(')}, expected 17")
        return 1
    print("M2 OK    the mutant drops exactly the gate-mint row (17 step rows remain)")

    # the mutant imports the 1Q-requires chain verbatim (it IS the 1Q
    # machine minus one row); rename the module so it cannot be confused
    # with the machine of record, and append the QS stall rows.
    mut = mut.replace("module SRW3N-ABS-Q", "module SRW3N-ABS-MUT-OMIT-GATEMINT-S", 1)
    mut = mut.replace('requires "srw3closure-j-m4.k"',
                      'requires "../../phase1n/semantics/srw3closure-j-m4.k"', 1)
    mut += "\n" + HEADER
    # the QS stall rows, verbatim from the generated QS file body
    body_start = qs_src.index("  rule <k> aExecJ(A1:AOk, A2:ASrc) => .K ... </k>")
    body_end = qs_src.index("endmodule")
    mut += "module SRW3N-ABS-MUT-OMIT-GATEMINT\n  imports SRW3N-ABS-MUT-OMIT-GATEMINT-S\n"
    mut += "\n  // ==== the QS ER-1 stall rows (verbatim from the generated QS variant) ====\n"
    mut += qs_src[body_start:body_end]
    mut += "endmodule\n"
    # fix the requires path inside the appended body (none needed: same module tree)
    new = mut.replace(HEADER, "")

    if OUT.exists():
        if OUT.read_text() != new:
            print("M3 FAILED roundtrip mismatch")
            return 1
        print(f"M3 OK    roundtrip byte-identical ({len(new)} bytes)")
    else:
        OUT.write_text(new)
        print(f"WROTE {OUT} ({len(new)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
