#!/usr/bin/env python3
# =============================================================================
# SRW3 Phase 1S — generator for the additive relation module
#                    (phase1s/scripts/make_rel_1s.py -> phase1s/semantics/rel-machine.k)
#
# Fail-closed, roundtrip-verified, deterministic. The module ADDS the §2
# definitions of record (CountRel / qToQE / StateRel) to the frozen QS
# machine of record — the frozen files themselves are NEVER edited.
#
# Checks (all must pass before the file is written):
#   R1  the frozen 1P TDRR source sha256 anchor of record
#   R2  the frozen 1Q machine source sha256 anchor of record
#   R3  the generated QS variant (the 1R machine of record) sha256 anchor
#   R4  the emitted file is deterministic: regenerating over the existing
#       file produces byte-identical output (roundtrip)
# Level III only; no consensus-integration claim.
# =============================================================================
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "phase1s" / "semantics" / "rel-machine.k"

ANCHORS = {
    "1P_TDRR": (
        REPO / "phase1p" / "semantics" / "abs-machine-tdrr.k",
        "448db6a46101d1f848a7ad364fc07a06cc99a903b4615afc0e5753ca0d8db511",
    ),
    "1Q_MACHINE": (
        REPO / "phase1q" / "semantics" / "abs-machine-q.k",
        "2e938fcb8939e0efe15e554687947b4dc44ece9a6a843f293799a18204e5383f",
    ),
    "1R_QS": (
        REPO / "phase1r" / "semantics" / "abs-machine-qs.k",
        "b526e2997e8f3f0d54fbb0a76ef0e1d718fae9afcffd6610bf383fb99cd3bbec",
    ),
}

TEMPLATE = '''// =============================================================================
// SRW3 PHASE 1S — THE STATE CORRESPONDENCE MODULE (GENERATED — DO NOT EDIT)
//                    (phase1s/semantics/rel-machine.k)
//
// GENERATED by phase1s/scripts/make_rel_1s.py. Regenerate; never edit.
//
// ADDITIVE over the frozen QS machine of record (imports ONLY
// SRW3N-ABS-QS; the frozen files are untouched). Defines the §2 relations
// of record (spec/state-correspondence.md):
//
//   CountRel(P, I)  <=>  I ==Int countToInt(P)      the count-level relation
//   qToQE(SQ)                                        the definitional image
//   StateRel(SQ, SE)                                 the full-state relation
//     the shared config/auth bits (C, T), the slot counter (N), the safety
//     flag (SF) and the diagnostic (D) are enforced at MATCH time by the
//     shared pattern variables (the mirror pattern reuses them) — the
//     KORE unifier route, which the probes showed to be reliable, unlike
//     ==Bool equality chains over shared symbolic variables;
//     (d) both pools related by CountRel — no silent weakening
//     (e) the branch tag consistent with the init-state bits on BOTH sides
//         (the mirror's bits ARE the shared C, T — one conjunct set governs
//         both sides) AND the tag itself in the legal range {0, 1} (an
//         incoherent tag such as 7 would otherwise slip through the
//         implications vacuously — the range conjunct refuses it)
//
// The integer-model safety predicate of record is ABSInvE (the 1P ABSInvT
// meaning verbatim, declared in the frozen QS module §G — including the
// tag-1 nonnegativity conjuncts). The constructor-count safety predicate
// of record is ABSInvQ. The two are NEVER identified.
// Level III only; no consensus-integration claim.
// =============================================================================

requires "../../phase1r/semantics/abs-machine-qs.k"

module SRW3N-REL-S
  imports SRW3N-ABS-QS

  // ===========================================================================
  // §1 CountRel — the count-level representation relation (exact)
  // ===========================================================================
  syntax Bool ::= CountRel ( PoolCount , Int ) [function, total]
  rule CountRel(P:PoolCount, I:Int) => I ==Int countToInt(P)

  // ===========================================================================
  // §2 The definitional image (the Q -> Int-mirror direction)
  // ===========================================================================
  syntax AStateQE ::= qToQE ( AStateQ ) [function, total]
  rule qToQE(absStQ(_:Int, C:Bool, T:Bool, G:PoolCount, E:PoolCount,
                    N:Int, SF:Bool, D:ADiag))
    => absStQE(C, T, countToInt(G), countToInt(E), N, SF, D)

  // ===========================================================================
  // §3 StateRel — the full-state representation relation (conjunctive;
  //    every representation-specific condition explicit; no disjunction
  //    at the top, no if-then-else)
  // ===========================================================================
  syntax Bool ::= StateRel ( AStateQ , AStateQE ) [function, total]
  rule StateRel(absStQ(TG:Int, C:Bool, T:Bool, G:PoolCount, E:PoolCount,
                       N:Int, SF:Bool, D:ADiag),
                absStQE(C, T, G2:Int, E2:Int, N,
                        SF, D))
    => CountRel(G, G2) andBool CountRel(E, E2)
       andBool TG >=Int 0 andBool TG <=Int 1
       andBool (TG ==Int 1 impliesBool (C  andBool T ))
       andBool (TG ==Int 0 impliesBool (notBool C andBool notBool T))

endmodule
'''


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    ok = True
    for name, (path, expected) in ANCHORS.items():
        got = sha256(path)
        if got != expected:
            print(f"R-CHECK FAILED {name}: sha256 {got} != anchored {expected}")
            ok = False
        else:
            print(f"R-ANCHOR OK {name}: {got[:16]}…")
    if not ok:
        print("make_rel_1s: FAIL-CLOSED (frozen-source anchor mismatch)")
        return 1

    new = TEMPLATE
    if OUT.exists():
        old = OUT.read_text()
        if old == new:
            print(f"R4 OK  roundtrip byte-identical ({len(new)} bytes)")
            return 0
        print(f"R4 FAILED roundtrip: existing file {len(old)} bytes != generated {len(new)} bytes")
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(new)
    print(f"WROTE {OUT} ({len(new)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
