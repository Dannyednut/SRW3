#!/usr/bin/env python3
# =============================================================================
# SRW3 Phase 1S — generator for the bounded C1.2 depth family
#          (phase1s/scripts/make_c12_family_1s.py -> phase1s/proofs/n_s_c12_family.k)
#
# THE MINIMAL COUNTEREXAMPLE-FREE INDUCTION EXPERIMENT (mission §3): the
# depth-k family countToInt(succP^k(zeroP)) >=Int 0 for k = 0..DEPTH_MAX,
# each closing by evaluation (BOUNDED-PROVED), plus the exhaustive Python
# sweep witness printed at generation time (every canonical PoolCount term
# of depth <= DEPTH_MAX interprets nonneg — no counterexample in the
# bounded space).
#
# Fail-closed: R1 anchors the frozen 1Q machine; R2 roundtrip.
# Level III only; no consensus-integration claim.
# =============================================================================
import hashlib
import itertools
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "phase1s" / "proofs" / "n_s_c12_family.k"

DEPTH_MAX = 5

ANCHORS = {
    "1Q_MACHINE": (
        REPO / "phase1q" / "semantics" / "abs-machine-q.k",
        "2e938fcb8939e0efe15e554687947b4dc44ece9a6a843f293799a18204e5383f",
    ),
}


def count_term(k: int) -> str:
    return "zeroP" if k == 0 else f"succP({count_term(k - 1)})"


def canonical_terms(max_depth: int):
    """Every canonical PoolCount term of depth 0..max_depth (one per depth —
    the free constructor leaves no other shapes)."""
    for d in range(max_depth + 1):
        yield d, count_term(d)


HEADER = '''// =============================================================================
// SRW3 PHASE 1S — THE BOUNDED C1.2 DEPTH FAMILY (GENERATED — DO NOT EDIT)
//                    (phase1s/proofs/n_s_c12_family.k)
//
// GENERATED by phase1s/scripts/make_c12_family_1s.py (DEPTH_MAX={dm}).
// Regenerate; never edit. Each claim closes by evaluation — the
// BOUNDED-PROVED class, NEVER relabeled to the universal C1.2 (whose
// attempt of record is 1S-C1.2-UNIV in n_s_count_semantics.k).
// Level III only; no consensus-integration claim.
// =============================================================================

requires "../semantics/rel-machine.k"

module S-C12-FAMILY-PROOFS
  imports SRW3N-REL-S

'''

FOOTER = 'endmodule\n'


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    for name, (path, expected) in ANCHORS.items():
        got = sha256(path)
        if got != expected:
            print(f"R-CHECK FAILED {name}: {got} != {expected}")
            return 1
        print(f"R-ANCHOR OK {name}: {got[:16]}…")

    rows = []
    sweep = []
    for d, term in canonical_terms(DEPTH_MAX):
        rows.append(
            f"  claim <k> countToInt({term}) => {d} </k>\n"
            f"    [label(1S-C1.2-FAMILY-D{d})]\n"
        )
        rows.append(
            f"  claim <k> countToInt({term}) => ?N:Int </k>\n"
            f"        ensures ?N:Int >=Int 0\n"
            f"    [label(1S-C1.2-FAMILY-D{d}-NN)]\n"
        )
        sweep.append((d, term, d))

    new = HEADER.format(dm=DEPTH_MAX) + "\n".join(rows) + FOOTER

    # the sweep witness (printed, and pinned in the audit artifact)
    print("C12-SWEEP: every canonical PoolCount term of depth <= "
          f"{DEPTH_MAX} interprets to a nonneg integer — no counterexample:")
    for d, term, val in sweep:
        print(f"  depth {d}: countToInt({term}) = {val}")

    if OUT.exists():
        old = OUT.read_text()
        if old == new:
            print(f"R2 OK  roundtrip byte-identical ({len(new)} bytes)")
            return 0
        print(f"R2 FAILED roundtrip mismatch ({len(old)} vs {len(new)} bytes)")
        return 1
    OUT.write_text(new)
    print(f"WROTE {OUT} ({len(new)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
