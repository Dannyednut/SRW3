#!/usr/bin/env python3
"""
SRW3 Phase 1M — Workstream B: build the M2 machine (the hash-backend
redirect) from the M1 machine.

M2 = M1 (the L-FINDING-1-repaired machine, srw3closure-j-m1.k) with EXACTLY
the following disclosed edits and NOTHING else:
  1. the M2 header block (documentation; records the M1 sha256);
  2. `requires "keccak256_total.k"` (the total evaluator module, same dir);
  3. module rename SRW3CLOSURE-J-M1 -> SRW3CLOSURE-J-M2;
  4. `imports KECCAK256-TOTAL` (makes Keccak256T visible to the redirect);
  5. ONE priority rule: `rule Keccak256raw(B:Bytes) => Keccak256T(B)`
     — the machine-side hash redirect.  The FROZEN LinH equation
     (k/phase1d/srw3lin.k: `rule LinH(B:Bytes) => Keccak256raw(B)`, default
     priority) stays in the definition UNTOUCHED and is unreachable: the
     priority rule always matches, so every machine hash flows through the
     total evaluator.  No semantic change on concrete inputs (the evaluator
     is pinned byte-for-byte to the hook on the validation vectors); on
     symbolic inputs the machine now materializes a DEFINED opaque term
     where the hook was UNDEFINED — the removal of blocker B1.

The redirect was mechanically verified pre-reset and is re-verified by the
M2 validation runs: the LLVM krun computes machine hashes WITHOUT the KRYPTO
hook namespaces (the discriminator: if the frozen hook rule fired, the run
would fail with the hook missing), and the T1-M2 anchor equals the frozen
record 295e0b6d... byte-for-byte.

Roundtrip discipline (make_m1.py precedent): the emitted file is verified
to differ from M1 by EXACTLY the disclosed lines.
"""
import hashlib
import re
from pathlib import Path

REPO = Path("/home/z/my-project/srw3-1m")
M1 = REPO / "phase1m/semantics/srw3closure-j-m1.k"
OUT = REPO / "phase1m/semantics/srw3closure-j-m2.k"
DEMO_IN = REPO / "phase1m/semantics/srw3closure-j-m1-demo.k"
DEMO_OUT = REPO / "phase1m/semantics/srw3closure-j-m2-demo.k"

src = M1.read_text()
m1_sha = hashlib.sha256(src.encode()).hexdigest()

HEADER = f"""\
// =============================================================================
// SRW3 PHASE 1M — M2: THE PROOF-BACKEND MACHINE (the hash redirect; the
//                    separately justified Workstream-B machine version)
//                    (phase1m/semantics/srw3closure-j-m2.k)
//
// M2 = M1 (the L-FINDING-1-repaired machine; scripts/make_m1.py; sha256
// {m1_sha}) with EXACTLY FIVE disclosed edits and NOTHING else:
//   1. this header;
//   2. `requires "keccak256_total.k"` — the TOTAL DETERMINISTIC KECCAK-256
//      EVALUATOR (pure K, no hooks; generated by
//      scripts/gen_keccak_total_packed.py; 7/7 vectors on BOTH backends);
//   3. the module rename SRW3CLOSURE-J-M1 -> SRW3CLOSURE-J-M2;
//   4. `imports KECCAK256-TOTAL`;
//   5. ONE priority rule redirecting the machine's hash PRIMITIVE:
//         rule Keccak256raw(B:Bytes) => Keccak256T(B)
//      The frozen KRYPTO hook stays in the definition (declared in the
//      imported krypto.md) but is unreachable: user equations on a hooked
//      symbol are tried before the native implementation, and this equation
//      always matches.  EVERY hash caller in the closure flows through it:
//      LinH (k/phase1d/srw3lin.k — StateRootJ, ProtoRootR3, JCatalogRootJ,
//      EvidenceIDJ, the anchors) AND the frozen 1E authority path
//      (phase1e/semantics/srw3auth.k: AuthLeafList / AuthWalkAux /
//      AuthWalkAuxList call Keccak256raw DIRECTLY — discovered by the
//      stuck-term discriminator on the first M2 build, which redirected
//      only LinH).
//
// WHY (the handoff §3 Workstream B): the Haskell backend has NO evaluator
// for the KRYPTO Keccak256raw hook over symbolic/hash-containing arguments,
// so every proof path materializing such a hash application died with an
// undischargeable #Ceil (the B1 boundary; 11 retained 1L blockers).  With
// the redirect, the machine materializes Keccak256T(...) — a DEFINED term
// by construction ([function,total] + the padding/absorb rule partition) —
// where it previously materialized an UNDEFINED hook application.  On
// concrete inputs the redirect is semantics-preserving: the evaluator is
// pinned byte-for-byte to the hook on the validation vectors, and the M2
// LLVM transcripts reproduce the frozen anchor bytes.
//
// DISCRIMINATOR of the redirect: the M2 LLVM krun computes machine hashes
// WITHOUT --hook-namespaces KRYPTO and without the krypto shim (if the
// frozen hook rule fired, the run would die with the hook missing).  The
// frozen machine and the M1 machine keep the real hook (their tiers are
// unchanged); M2 is the PROOF-FACING variant.  No new hash EQUALITY,
// collision resistance, preimage resistance, or injectivity is assumed
// anywhere; the M2 negative controls enforce that totality grants no
// equality power.
// =============================================================================
"""

# --- the five edits ---------------------------------------------------------
assert src.startswith("//"), "M1 expected to start with its header"
body = src

# (2) requires
old_req = 'requires "../../phase1g/semantics/srw3authz.k"'
assert body.count(old_req) == 1
body = body.replace(old_req, old_req + '\nrequires "keccak256_total.k"')

# (3) module rename
assert body.count("module SRW3CLOSURE-J-M1") == 1
body = body.replace("module SRW3CLOSURE-J-M1", "module SRW3CLOSURE-J-M2")

# (4) import
old_imp = "  imports SRW3AUTHZ"
assert body.count(old_imp) == 1
body = body.replace(old_imp, old_imp + "\n  imports KECCAK256-TOTAL")

# (5) the redirect rule — inserted right after the import block, before §A
anchor = "  // ===========================================================================\n  // §A."
idx = body.index(anchor)
RULE = """  // ---------------------------------------------------------------------------
  // THE M2 HASH REDIRECT (Workstream B; the ONLY rule added to the machine).
  // Keccak256raw is the machine's hash PRIMITIVE (the KRYPTO hook).  User
  // equations on a hooked symbol are tried before the native implementation,
  // and this equation always matches (no guard): EVERY machine hash flows
  // through the total evaluator Keccak256T.  This covers LinH
  // (k/phase1d/srw3lin.k — StateRootJ / ProtoRootR3 / JCatalogRootJ /
  // EvidenceIDJ / the anchors) AND the frozen 1E authority path
  // (phase1e/semantics/srw3auth.k: AuthLeafList / AuthWalkAux /
  // AuthWalkAuxList call Keccak256raw directly).  The frozen hook stays
  // declared and linked but is unreachable.  No new hash property is
  // assumed; the evaluator is pinned to the hook on the validation vectors.
  // ---------------------------------------------------------------------------
  rule Keccak256raw(B:Bytes) => Keccak256T(B)

"""
body = body[:idx] + RULE + body[idx:]

# (1) header on top
out_text = HEADER + "\n" + body
OUT.write_text(out_text)

# --- roundtrip verification -------------------------------------------------
chk = out_text
chk = chk.replace(HEADER + "\n", "", 1)
chk = chk.replace(old_req + '\nrequires "keccak256_total.k"', old_req, 1)
chk = chk.replace("module SRW3CLOSURE-J-M2", "module SRW3CLOSURE-J-M1", 1)
chk = chk.replace(old_imp + "\n  imports KECCAK256-TOTAL", old_imp, 1)
# strip the inserted rule block
i = chk.index(RULE)
chk = chk[:i] + chk[i + len(RULE):]
assert chk == src, "ROUNDTRIP FAILED: emitted file does not reduce to M1"
print(f"M2 written: {OUT}")
print(f"M1 sha256: {m1_sha}")
print("roundtrip: OK (M2 = M1 + exactly the 5 disclosed edits)")

# --- demo module ------------------------------------------------------------
# LINE-ANCHORED replacements: the demo's header COMMENT mentions the same
# strings (the first build rewrote the comment and left the real requires
# pointing at M1 — the compiled definition was silently the M1 machine).
demo = DEMO_IN.read_text()
d2 = demo.replace('\nrequires "srw3closure-j-m1.k"', '\nrequires "srw3closure-j-m2.k"', 1)
d2 = d2.replace("\nmodule SRW3CLOSURE-J-M1-DEMO", "\nmodule SRW3CLOSURE-J-M2-DEMO", 1)
d2 = d2.replace("\n  imports SRW3CLOSURE-J-M1", "\n  imports SRW3CLOSURE-J-M2", 1)
assert '\nrequires "srw3closure-j-m2.k"' in d2, "real requires line not replaced"
assert '\nmodule SRW3CLOSURE-J-M2-DEMO' in d2, "real module line not replaced"
assert '\n  imports SRW3CLOSURE-J-M2' in d2, "real imports line not replaced"
d2 = d2.replace(
    "// SRW3 PHASE 1M — M1 DEMONSTRATION MODULE (VERSIONED COPY)",
    "// SRW3 PHASE 1M — M2 DEMONSTRATION MODULE (VERSIONED COPY; make_m2.py)", 1)
d2 = d2.replace(
    "srw3closure-j-m1.k)",
    "srw3closure-j-m2.k — the M2 hash-redirect machine; make_m2.py)", 1)
d2 = d2.replace("scripts/make_m1.py", "scripts/make_m2.py", 1)
d2 = d2.replace("scripts/make_m1_demo.py", "scripts/make_m2.py", 1)
d2 = d2.replace("The T11-M1\n// krun transcript", "The T11-M2\n// krun transcript", 1)
d2 = d2.replace("T11-M1", "T11-M2").replace("T1-M1", "T1-M2")
d2 = d2.replace("M1 REPAIRED machine", "M2 hash-redirect machine")
DEMO_OUT.write_text(d2)
print(f"M2 demo written: {DEMO_OUT}")
